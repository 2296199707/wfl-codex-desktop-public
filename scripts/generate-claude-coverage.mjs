import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  CLAUDE_CAPABILITY_STATES,
  CLAUDE_PROTOCOL_BASELINE,
  CLAUDE_REQUIRED_INTERNAL_OPTIONS,
  claudeProtocolCoverageSections,
} from "../lib/claude-protocol-coverage.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const projectDirectory = path.dirname(path.dirname(scriptPath));
const fixturePath = path.join(
  projectDirectory,
  "test",
  "fixtures",
  "claude-code-2.1.236-capabilities.json",
);
const outputPath = path.join(projectDirectory, "docs", "claude-code-2.1.236-coverage.md");

if (path.resolve(process.argv[1] || "") === scriptPath) {
  try {
    const unknown = process.argv.slice(2).filter((argument) => argument !== "--check");
    if (unknown.length) throw new Error(`Unknown Claude coverage argument: ${unknown[0]}`);
    const fixture = JSON.parse(await fs.readFile(fixturePath, "utf8"));
    const sections = claudeProtocolCoverageSections();
    await validateClaudeCoverage({ fixture, sections, projectDirectory });
    const document = renderClaudeCoverageDocument({ fixture, sections });
    if (process.argv.includes("--check")) {
      const current = await fs.readFile(outputPath, "utf8").catch((error) => {
        if (error.code === "ENOENT") return "";
        throw error;
      });
      if (current !== document) {
        throw new Error("Claude capability matrix is stale; run npm run claude:coverage");
      }
      process.stdout.write(`${path.relative(projectDirectory, outputPath)} is current\n`);
    } else {
      await fs.writeFile(outputPath, document, { mode: 0o644 });
      process.stdout.write(`Generated ${path.relative(projectDirectory, outputPath)}\n`);
    }
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

export async function validateClaudeCoverage({ fixture, sections, projectDirectory: root }) {
  if (fixture?.baseline !== CLAUDE_PROTOCOL_BASELINE || fixture.version !== baselineVersion()) {
    throw new Error("Claude coverage fixture does not match the reviewed baseline");
  }
  const expected = new Map([
    ["options", fixture.helpOptions],
    ["commands", fixture.commands],
    ["topLevelEvents", fixture.topLevelEvents],
    ["streamEvents", fixture.streamEvents],
    ["systemEvents", fixture.systemEvents],
    ["controlRequests", fixture.controlRequestSubtypes],
    ["dialogKinds", fixture.dialogKinds],
    ["permissionModes", fixture.permissionModes],
    ["effortLevels", fixture.effortLevels],
  ]);
  for (const section of sections) {
    const methods = sorted(section.entries.map((item) => item.method));
    if (JSON.stringify(methods) !== JSON.stringify(sorted(expected.get(section.key) || []))) {
      throw new Error(`Claude ${section.key} coverage no longer matches the reviewed fixture`);
    }
    for (const item of section.entries) {
      if (!CLAUDE_CAPABILITY_STATES.has(item.state)) {
        throw new Error(`Claude ${section.key} capability ${item.method} has an invalid state`);
      }
      if (!item.evidence || typeof item.evidence !== "object") {
        throw new Error(`Claude ${section.key} capability ${item.method} has no evidence record`);
      }
      if (
        ["runtime", "internal", "custom-equivalent", "partial"].includes(item.state)
        && (!item.evidence.server?.length || !item.evidence.tests?.length)
      ) {
        throw new Error(`Implemented Claude capability ${item.method} lacks server or test evidence`);
      }
      for (const kind of ["server", "ui", "tests"]) {
        if (!Array.isArray(item.evidence[kind])) {
          throw new Error(`Claude capability ${item.method} has invalid ${kind} evidence`);
        }
        for (const reference of item.evidence[kind]) {
          const filename = String(reference).split("#", 1)[0];
          if (!filename || path.isAbsolute(filename) || filename.startsWith("..")) {
            throw new Error(`Claude capability ${item.method} has an unsafe evidence reference`);
          }
          await fs.access(path.join(root, filename));
        }
      }
    }
  }
  if (
    JSON.stringify(sorted(CLAUDE_REQUIRED_INTERNAL_OPTIONS))
    !== JSON.stringify(sorted(fixture.requiredInternalOptions || []))
  ) {
    throw new Error("Claude internal option coverage no longer matches the reviewed fixture");
  }
}

export function renderClaudeCoverageDocument({ fixture, sections }) {
  const allEntries = sections.flatMap((section) => section.entries);
  const counts = Object.fromEntries([...CLAUDE_CAPABILITY_STATES].map((state) => [
    state,
    allEntries.filter((item) => item.state === state).length,
  ]));
  const lines = [
    "# Claude Code 2.1.236 capability coverage",
    "",
    "> Generated by `npm run claude:coverage`. Do not edit this file by hand.",
    "",
    `Reviewed baseline: \`${fixture.baseline}\``,
    `CLI commit: \`${fixture.commit}\``,
    `Help semantic SHA-256: \`${fixture.helpSemanticSha256}\``,
    "",
    "## Summary",
    "",
    "| State | Count | Meaning |",
    "| --- | ---: | --- |",
    `| Implemented at runtime | ${counts.runtime} | Passed to or consumed from the native Claude runtime |`,
    `| Implemented internally | ${counts.internal} | Used behind a guarded WFL server workflow |`,
    `| WFL equivalent | ${counts["custom-equivalent"]} | Native behavior supplied through a safer WFL workflow |`,
    `| Partially implemented | ${counts.partial} | Main workflow exists but the native lifecycle is not complete |`,
    `| Planned | ${counts.planned} | Reviewed and included in the active implementation goal |`,
    `| Deliberately deferred | ${counts.deferred} | Reviewed but excluded pending a separate security or product decision |`,
    `| Not applicable | ${counts["not-applicable"]} | Replaced by the browser-owned application surface |`,
    "",
  ];
  for (const section of sections) {
    lines.push(`## ${section.label}`, "");
    lines.push("| Capability | State | Surface | Server evidence | UI evidence | Test evidence | Notes |");
    lines.push("| --- | --- | --- | --- | --- | --- | --- |");
    for (const item of section.entries) {
      lines.push([
        `| \`${escapeCell(item.method)}\``,
        stateLabel(item.state),
        escapeCell(item.surface),
        evidenceCell(item.evidence.server),
        evidenceCell(item.evidence.ui),
        evidenceCell(item.evidence.tests),
        notesCell(item),
      ].join(" | ") + " |");
    }
    lines.push("");
  }
  lines.push(
    "## Upgrade gate",
    "",
    "Candidate and ordinary-server quick checks call the real Claude compatibility probe. "
      + "A version or reviewed CLI commit change, help semantic change, added or removed option/command, or unreviewed "
      + "control surface fails the gate before activation. Unknown runtime events are fingerprinted "
      + "and ignored; unknown control requests are denied.",
  );
  return `${lines.join("\n")}\n`;
}

function stateLabel(state) {
  return ({
    runtime: "Implemented",
    internal: "Implemented (internal)",
    "custom-equivalent": "Implemented (WFL equivalent)",
    partial: "Partial",
    planned: "Planned",
    deferred: "Deliberately deferred",
    "not-applicable": "Not applicable",
  })[state] || state;
}

function evidenceCell(entries) {
  if (!entries?.length) return "—";
  return entries.map((entry) => `\`${escapeCell(entry)}\``).join("<br>");
}

function notesCell(item) {
  const notes = [
    item.reason,
    item.replacement ? `Replacement: ${item.replacement}` : null,
    item.administratorRequired ? "Administrator approval required" : null,
    item.highRisk ? "High risk" : null,
  ].filter(Boolean);
  return notes.length ? escapeCell(notes.join("; ")) : "—";
}

function escapeCell(value) {
  return String(value || "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function sorted(values) {
  return [...values].map(String).sort((left, right) => left.localeCompare(right, "en"));
}

function baselineVersion() {
  return CLAUDE_PROTOCOL_BASELINE.match(/(\d+\.\d+\.\d+)$/)?.[1] || null;
}
