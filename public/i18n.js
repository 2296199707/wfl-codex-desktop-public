  function normalizeLanguage(value) {
    const normalized = String(value || "").trim().toLowerCase().replace(/_/g, "-");
    return normalized === "en" || normalized.startsWith("en-") ? ENGLISH_LANGUAGE : DEFAULT_LANGUAGE;
  }

  function translateCore(value) {
    if (!value || !/[\u3400-\u9fff]/u.test(value)) return value;
    const exact = ENGLISH_TRANSLATIONS[value];
    if (exact) return exact;

    if (value.includes(" · ")) {
      const parts = value.split(" · ");
      const translated = parts.map((part) => translateCore(part));
      if (translated.some((part, index) => part !== parts[index])) return translated.join(" · ");
    }

    for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
      if (pattern.test(value)) return value.replace(pattern, replacement);
    }
    return value;
  }

  function translateText(value, language = ENGLISH_LANGUAGE) {
    if (typeof value !== "string" || normalizeLanguage(language) !== ENGLISH_LANGUAGE) return value;
    const match = /^(\s*)([\s\S]*?)(\s*)$/u.exec(value);
    if (!match || !match[2]) return value;
    return `${match[1]}${translateCore(match[2])}${match[3]}`;
  }

  function isProtectedElement(element) {
    return Boolean(element?.closest?.(PROTECTED_CONTENT_SELECTOR));
  }

  function translateNodeValue(value, language, parentElement) {
    return isProtectedElement(parentElement) ? value : translateText(value, language);
  }

  function resolveTranslationState(previous, value, language) {
    const normalizedLanguage = normalizeLanguage(language);
    if (normalizedLanguage === DEFAULT_LANGUAGE) {
      const source = previous?.language === ENGLISH_LANGUAGE && value === previous.rendered
        ? previous.source
        : value;
      return { source, rendered: source, language: normalizedLanguage };
    }
    if (previous?.language === ENGLISH_LANGUAGE && value === previous.rendered) return previous;
    const source = previous?.language === DEFAULT_LANGUAGE && value === previous.source
      ? previous.source
      : value;
    return {
      source,
      rendered: translateText(source, normalizedLanguage),
      language: normalizedLanguage,
    };
  }

