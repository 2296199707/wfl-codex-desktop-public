  function translateTextNode(node, language) {
    if (!node || isProtectedElement(node.parentElement)) return;
    const value = node.nodeValue;
    if (typeof value !== "string" || !value.trim()) return;
    const previous = textState.get(node);

    const next = resolveTranslationState(previous, value, language);
    if (next === previous) return;
    next.rendered = translateNodeValue(next.source, language, node.parentElement);
    textState.set(node, next);
    if (next.rendered !== value) node.nodeValue = next.rendered;
  }

  function translateAttribute(element, attribute, language) {
    if (!element?.hasAttribute?.(attribute) || isProtectedElement(element)) return;
    const value = element.getAttribute(attribute);
    if (!value) return;
    let states = attributeState.get(element);
    if (!states) {
      states = new Map();
      attributeState.set(element, states);
    }
    const previous = states.get(attribute);

    const next = resolveTranslationState(previous, value, language);
    if (next === previous) return;
    states.set(attribute, next);
    if (next.rendered !== value) element.setAttribute(attribute, next.rendered);
  }

  function translateElement(element, language) {
    if (!element || isProtectedElement(element)) return;
    for (const attribute of TRANSLATED_ATTRIBUTES) translateAttribute(element, attribute, language);
  }

  function translateTree(root, language = currentLanguage) {
    if (!root) return;
    if (root.nodeType === 3) {
      translateTextNode(root, language);
      return;
    }
    if (root.nodeType !== 1 && root.nodeType !== 9 && root.nodeType !== 11) return;
    if (root.nodeType === 1 && isProtectedElement(root)) return;
    if (root.nodeType === 1) translateElement(root, language);

    const ownerDocument = root.ownerDocument || root;
    const walker = ownerDocument.createTreeWalker(root, 1 | 4);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === 1) translateElement(node, language);
      else translateTextNode(node, language);
      node = walker.nextNode();
    }
  }

